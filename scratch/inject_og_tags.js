const cachePath = path.join(rootDir, 'src', 'data', 'keywordCache.json');
let keywordCache = {};
if (fs.existsSync(cachePath)) {
  keywordCache = JSON.parse(fs.readFileSync(cachePath, 'utf-8'));
}

const getVolume = (slug) => {
  return keywordCache[slug] ? keywordCache[slug].volume : -1;
};

const getBestKeyword = (slug, defaultName) => {
  return keywordCache[slug] && keywordCache[slug].best_keyword ? keywordCache[slug].best_keyword : defaultName;
};

// 2. Generate a physical .html file for every product
let generatedCount = 0;
for (const slug in productDetailsData) {
  if (getVolume(slug) === 0) continue;
  const product = productDetailsData[slug];
  
  const bestKeyword = getBestKeyword(slug, product.name);
  const title = product.seoTitle || `${bestKeyword} | Anchorstone Global Materials`;
  const description = product.seoDescription || product.sourceText;
  const image = product.heroImage;
  const url = `/materials/${slug}.html`;
  
  const schemaJson = {
    "@context": "https://schema.org",
    "@type": "Product",
    "name": bestKeyword,
    "image": `https://anchorstoneglobal.co.in${image}`,
    "description": description,
    "brand": {
      "@type": "Brand",
      "name": "Anchorstone Global"
    },
    "offers": {
      "@type": "Offer",
      "url": `https://anchorstoneglobal.co.in${url}`,
      "priceCurrency": "USD",
      "price": "0",
      "availability": "https://schema.org/InStock",
      "seller": {
        "@type": "Organization",
        "name": "Anchorstone Global LLP"
      }
    }
  };
  const productHtml = injectMeta(baseHtml, title, description, image, url, schemaJson);
  
  const productFilePath = path.join(materialsDir, `${slug}.html`);
  fs.writeFileSync(productFilePath, productHtml);
  generatedCount++;
}

