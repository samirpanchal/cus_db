// Read the base index.html generated by Vite
const indexPath = path.join(distDir, 'index.html');
const baseHtml = fs.readFileSync(indexPath, 'utf-8');

// Helper to inject meta tags into head
const injectMeta = (html, title, description, image, url, schemaJson) => {
  const fullUrl = `https://anchorstoneglobal.co.in${url}`;
  
  const metaTags = `
    <title>${title}</title>
    <meta name="description" content="${description}" />
    <link rel="canonical" href="${fullUrl}" />
    <meta property="og:title" content="${title}" />
    <meta property="og:description" content="${description}" />
    <meta property="og:image" content="https://anchorstoneglobal.co.in${image}" />
    <meta property="og:url" content="${fullUrl}" />
    <meta property="og:type" content="website" />
    <meta name="twitter:card" content="summary_large_image" />
    ${schemaJson ? `<script type="application/ld+json">\n${JSON.stringify(schemaJson)}\n    </script>` : ''}
  `;
  
  // Replace the default <title> tag with our rich meta tags
  return html.replace(/<title>.*?<\/title>/i, metaTags);
};

